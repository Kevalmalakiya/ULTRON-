package com.ultron.assistant

import org.json.JSONArray
import org.json.JSONObject
import java.io.ByteArrayOutputStream
import java.io.IOException
import java.net.HttpURLConnection
import java.net.URL

 data class UltronApiMessage(
    val role: String,
    val content: String
)

object UltronApiClient {
    private const val CONNECT_TIMEOUT_MS = 20_000
    private const val CHAT_READ_TIMEOUT_MS = 240_000
    private const val TTS_READ_TIMEOUT_MS = 180_000
    private const val MAX_AUDIO_BYTES = 24 * 1024 * 1024

    fun sendChat(
        baseUrl: String,
        apiKey: String,
        messages: List<UltronApiMessage>
    ): String {
        validateConfiguration(baseUrl, apiKey)

        val payloadMessages = JSONArray()
        messages.takeLast(12).forEach { message ->
            payloadMessages.put(
                JSONObject()
                    .put("role", message.role)
                    .put("content", message.content)
            )
        }

        val payload = JSONObject()
            .put("messages", payloadMessages)
            .put("max_new_tokens", 256)
            .put("temperature", 0.7)

        val connection = openPost(baseUrl, "/chat", apiKey, CHAT_READ_TIMEOUT_MS)
        try {
            connection.outputStream.bufferedWriter(Charsets.UTF_8).use { writer ->
                writer.write(payload.toString())
            }

            val status = connection.responseCode
            val responseText = readTextResponse(connection, status)
            if (status !in 200..299) {
                val detail = runCatching {
                    JSONObject(responseText).optString("detail").ifBlank { responseText }
                }.getOrDefault(responseText)
                throw IOException("Backend HTTP $status: $detail")
            }

            val reply = JSONObject(responseText).optString("reply").trim()
            if (reply.isBlank()) {
                throw IOException("The backend returned an empty reply.")
            }
            return reply
        } finally {
            connection.disconnect()
        }
    }

    /** Downloads a PCM WAV generated by the authenticated Kokoro /tts endpoint. */
    fun synthesizeSpeech(
        baseUrl: String,
        apiKey: String,
        text: String,
        language: String,
        speed: Float,
        onConnection: (HttpURLConnection?) -> Unit = {}
    ): ByteArray {
        validateConfiguration(baseUrl, apiKey)
        require(text.isNotBlank()) { "Speech text is empty." }
        require(language == "en" || language == "hi") { "Unsupported speech language." }
        require(speed in 0.75f..1.25f) { "Speech speed is outside the supported range." }

        val payload = JSONObject()
            .put("text", text)
            .put("language", language)
            .put("speed", speed.toDouble())

        val connection = openPost(baseUrl, "/tts", apiKey, TTS_READ_TIMEOUT_MS)
        onConnection(connection)
        try {
            connection.setRequestProperty("Accept", "audio/wav")
            connection.outputStream.use { stream ->
                stream.write(payload.toString().toByteArray(Charsets.UTF_8))
                stream.flush()
            }

            val status = connection.responseCode
            if (status !in 200..299) {
                val errorBody = readTextResponse(connection, status)
                val detail = runCatching {
                    JSONObject(errorBody).optString("detail").ifBlank { errorBody }
                }.getOrDefault(errorBody)
                throw IOException("Kokoro TTS HTTP $status: $detail")
            }

            val contentType = connection.contentType.orEmpty()
            if (!contentType.contains("audio/wav", ignoreCase = true) &&
                !contentType.contains("audio/x-wav", ignoreCase = true)
            ) {
                throw IOException("TTS returned an unexpected content type: $contentType")
            }

            val audio = connection.inputStream.use { input ->
                val output = ByteArrayOutputStream()
                val buffer = ByteArray(8192)
                var total = 0
                while (true) {
                    val count = input.read(buffer)
                    if (count < 0) break
                    total += count
                    if (total > MAX_AUDIO_BYTES) {
                        throw IOException("Generated audio exceeds the 24 MB safety limit.")
                    }
                    output.write(buffer, 0, count)
                }
                output.toByteArray()
            }

            if (audio.size < 44 ||
                audio[0] != 'R'.code.toByte() ||
                audio[1] != 'I'.code.toByte() ||
                audio[2] != 'F'.code.toByte() ||
                audio[3] != 'F'.code.toByte()
            ) {
                throw IOException("The TTS response is not a valid WAV file.")
            }
            return audio
        } finally {
            onConnection(null)
            connection.disconnect()
        }
    }

    private fun validateConfiguration(baseUrl: String, apiKey: String) {
        require(baseUrl.trim().startsWith("https://", ignoreCase = true)) {
            "The API URL must begin with https://"
        }
        require(apiKey.isNotBlank()) { "API key is missing." }
    }

    private fun openPost(
        baseUrl: String,
        path: String,
        apiKey: String,
        readTimeout: Int
    ): HttpURLConnection {
        val cleanBaseUrl = baseUrl.trim().trimEnd('/')
        val connection = URL(cleanBaseUrl + path).openConnection() as HttpURLConnection
        connection.requestMethod = "POST"
        connection.connectTimeout = CONNECT_TIMEOUT_MS
        connection.readTimeout = readTimeout
        connection.doOutput = true
        connection.instanceFollowRedirects = true
        connection.setRequestProperty("Content-Type", "application/json; charset=utf-8")
        connection.setRequestProperty("X-API-Key", apiKey)
        return connection
    }

    private fun readTextResponse(connection: HttpURLConnection, status: Int): String {
        val stream = if (status in 200..299) connection.inputStream else connection.errorStream
        return stream?.bufferedReader(Charsets.UTF_8)?.use { it.readText() }.orEmpty()
    }
}
